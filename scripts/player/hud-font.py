#!/usr/bin/env python3
"""Subset the native HUD's Xolonium Regular font for offline numeric text.

    uv run --with UnityPy==1.25.3 --with fonttools --with brotli python scripts/player/hud-font.py

Writes crates/player/web/hud-font.css. Only numeric glyphs and original font
metadata are retained. No UI artwork is copied. --check compares the result
without changing it and requires the installed game.
"""
import base64
import io
import sys
from pathlib import Path

import UnityPy
from fontTools import subset
from fontTools.ttLib import TTFont

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import build_data

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / 'crates/player/web/hud-font.css'

def arguments(parser):
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--data', type=Path, default=Path.home() / 'Library/Application Support/Steam/steamapps/common/Mechabellum/Mechabellum.app/Contents/Resources/Data')

def main():
    args = build_data.arguments(__doc__, arguments)
    env = UnityPy.load(str(args.data / 'sharedassets0.assets'))
    face = None
    for obj in env.objects:
        if obj.assets_file.name != 'sharedassets0.assets' or obj.type.name != 'Font':
            continue
        font = obj.read()
        if 'xolonium' not in font.m_Name.lower() or not font.m_FontData:
            continue
        candidate = TTFont(io.BytesIO(bytes(font.m_FontData)), recalcTimestamp=False)
        if candidate['name'].getDebugName(2) == 'Regular':
            if face is not None:
                sys.exit('ambiguous Xolonium Regular font')
            face = candidate
    if face is None:
        sys.exit('missing Xolonium Regular font data')
    options = subset.Options()
    options.name_IDs = ['*']
    options.name_languages = ['*']
    smaller = subset.Subsetter(options=options)
    smaller.populate(text='0123456789:.-−—')
    smaller.subset(face)
    face.flavor = 'woff2'
    stream = io.BytesIO()
    face.save(stream)
    encoded = base64.b64encode(stream.getvalue()).decode()
    result = '\n'.join([
        '/* Generated by scripts/player/hud-font.py; numeric Xolonium Regular subset. */',
        '@font-face {', '  font-family: "Mechcore HUD";',
        f'  src: url("data:font/woff2;base64,{encoded}") format("woff2");',
        '  font-style: normal;', '  font-weight: 400;', '  font-display: swap;', '}', '',
    ])
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != result:
            sys.exit('HUD numeric font differs; regenerate it')
    else:
        OUTPUT.write_text(result)
    print(f'Numeric HUD font: {len(result)} bytes')

if __name__ == '__main__':
    main()
