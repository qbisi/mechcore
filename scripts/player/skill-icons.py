#!/usr/bin/env python3
"""Trace native front-facing skill symbols into the player's vector module.

Run on the machine with the installed game and its matching local data export:

    nix-shell -p potrace --run 'uv run --with UnityPy==1.25.3 --with pillow python scripts/player/skill-icons.py'

Requires UnityPy, Pillow and Potrace. Original bitmaps and intermediate traces
stay under work/player/skill-icons/. --check compares the generated module
without changing it; it still requires the game. No bitmap enters the player.
"""

import hashlib
import json
from pathlib import Path
import re
import shutil
import subprocess
import sys
import xml.etree.ElementTree as ET

import UnityPy
from PIL import Image

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import build_data

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / "crates/player/web/skill-icons.js"
SOURCES = {
    "missile_strike": 300001,
    "heavy_missile_strike": 300016,
    "nuke": 300004,
    "orbital_javelin": 300007,
    "incendiary_bomb": 100002,
    "sticky_oil_bomb": 400002,
    "acid_blast": 500002,
    "smoke_bomb": 600002,
    "ion_blast": 300006,
    "orbital_bombardment": 300003,
    "lightning_storm": 300005,
}


def arguments(parser):
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--data", type=Path, default=Path.home() / "Library/Application Support/Steam/steamapps/common/Mechabellum/Mechabellum.app/Contents/Resources/Data")


def commands(svg, size, bounds):
    _, height = size
    left, top, right, bottom = bounds
    scale = 52 / max(right-left, bottom-top)
    result = []

    def normalise(values):
        points = []
        for i, value in enumerate(values):
            value = value/10-(left+right)/2 if i % 2 == 0 else height-value/10-(top+bottom)/2
            value = round(value*scale, 3)
            points.append(0 if value == 0 else value)
        return points

    for path in ET.parse(svg).getroot().iter("{http://www.w3.org/2000/svg}path"):
        tokens = re.findall(r"[A-Za-z]|[-+]?(?:\d*\.\d+|\d+)(?:[eE][-+]?\d+)?", path.attrib["d"])
        at = 0
        x = y = sx = sy = 0
        operation = None
        while at < len(tokens):
            if tokens[at].isalpha():
                operation = tokens[at]
                at += 1
            kind, relative = operation.upper(), operation.islower()
            if kind == "Z":
                result.append(["Z"])
                x, y, operation = sx, sy, None
                continue
            count = {"M": 2, "L": 2, "C": 6}[kind]
            values = list(map(float, tokens[at:at+count]))
            at += count
            if relative:
                values = [v+(x if i % 2 == 0 else y) for i, v in enumerate(values)]
            x, y = values[-2:]
            result.append([kind, *normalise(values)])
            if kind == "M":
                sx, sy = x, y
                operation = "l" if relative else "L"
    return result


def main():
    args = build_data.arguments(__doc__, arguments)
    potrace = shutil.which("potrace")
    if not potrace:
        sys.exit("potrace is required; run through nix-shell -p potrace")
    rows = {r["id"]: r for group in build_data.level0("CommanderSkillGroupData").values()
            if isinstance(group, list) for r in group if isinstance(r, dict) and "id" in r}
    # SBUI artwork is pre-skewed for the native ground presentation. The card's
    # high-resolution focused variant is the front-facing silhouette we need.
    symbols = {kind: rows[ident]["iconName"]+"_f" for kind, ident in SOURCES.items()}
    out = ROOT / "work/player/skill-icons"
    out.mkdir(parents=True, exist_ok=True)
    env = UnityPy.load(str(args.data / "sharedassets0.assets"))
    found = {}
    for obj in env.objects:
        if obj.type.name != "Sprite":
            continue
        sprite = obj.read()
        if sprite.m_Name in symbols.values():
            path = out / f"{sprite.m_Name}.png"
            sprite.image.save(path)
            found[sprite.m_Name] = path
    missing = set(symbols.values())-found.keys()
    if missing:
        sys.exit(f"missing native front-facing sprites: {', '.join(sorted(missing))}")
    lines = ["// Generated by scripts/player/skill-icons.py from native front-facing _f alpha contours.",
             "// Alpha >= 128; Potrace: turdsize 0, alphamax 1, opttolerance 0.2.",
             "// Original bitmaps remain local. Do not edit these paths by hand.",
             "'use strict';", "", "const NativeSkillIcons = (() => {", "  const paths = {"]
    for kind, symbol in symbols.items():
        image = Image.open(found[symbol]).convert("RGBA")
        alpha = image.getchannel("A")
        bounds = alpha.point(lambda v: 255 if v >= 128 else 0).getbbox()
        if bounds is None:
            sys.exit(f"{symbol} has no visible silhouette")
        pbm = out / f"{symbol}.pbm"
        alpha.point(lambda v: 0 if v >= 128 else 255).convert("1", dither=Image.Dither.NONE).save(pbm)
        svg = out / f"{symbol}.svg"
        subprocess.run([potrace, str(pbm), "--svg", "--output", str(svg), "--turdsize", "0", "--alphamax", "1", "--opttolerance", "0.2"], check=True)
        shape = commands(svg, image.size, bounds)
        digest = hashlib.sha256(alpha.tobytes()).hexdigest()
        lines += [f"    // {symbol}; alpha SHA-256 {digest}",
                  f"    {kind}: {json.dumps(shape, separators=(',', ':'))},"]
    lines += ["  };", "  const methods = { M: 'moveTo', L: 'lineTo', C: 'bezierCurveTo', Z: 'closePath' };",
              "  return Object.fromEntries(Object.entries(paths).map(([kind, path]) => [kind, (c, ink) => {",
              "    c.fillStyle = ink; c.beginPath();",
              "    for (const [op, ...points] of path) c[methods[op]](...points);",
              "    c.fill();", "  }]));", "})();", ""]
    source = "\n".join(lines)
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != source:
            sys.exit("skill-icons.js differs; rerun scripts/player/skill-icons.py")
    else:
        OUTPUT.write_text(source)
    print(f"{len(symbols)} native skill icons {'match' if args.check else 'written'}")


if __name__ == "__main__":
    main()
